export function certificateUrl(value) {
  if (typeof value !== "string" || !value.trim()) return null;
  if (value.startsWith("/certificates/") && !value.includes("..")) return value;
  try {
    const url = new URL(value);
    return url.protocol === "https:" && !url.username && !url.password
      ? url.href
      : null;
  } catch {
    return null;
  }
}

export function validCertificates(records) {
  const ids = new Set();
  return (Array.isArray(records) ? records : []).filter((record) => {
    const valid =
      record &&
      typeof record.id === "string" &&
      record.id.trim() &&
      !ids.has(record.id) &&
      typeof record.title === "string" &&
      record.title.trim() &&
      typeof record.issuer === "string" &&
      record.issuer.trim() &&
      certificateUrl(record.document) &&
      certificateUrl(record.preview) &&
      [
        "category",
        "recipient",
        "provider",
        "issuedDate",
        "completionDate",
        "expirationDate",
        "credentialId",
        "duration",
        "description",
      ].every(
        (key) => record[key] == null || typeof record[key] === "string",
      ) &&
      (record.skills == null ||
        (Array.isArray(record.skills) &&
          record.skills.every((skill) => typeof skill === "string")));
    if (valid) ids.add(record.id);
    return Boolean(valid);
  });
}

export function certificateCategories(records) {
  return [...new Set(records.map((record) => record.category).filter(Boolean))];
}
